import { test, expect } from '@playwright/test';

test('complete homeowner flow calculates, optimizes, saves and downloads actual report data', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.locator('.application')).toHaveAttribute('data-ready','true');
  await page.getByRole('button', { name: 'Start free estimate' }).click();
  await expect(page.getByRole('heading', { name: 'Tell us about your project.' })).toBeVisible();
  await page.getByLabel('Project name', { exact: true }).fill('Our Pangasinan home');
  await page.getByLabel('Province', { exact: true }).selectOption('Pangasinan');
  await page.getByLabel('City / municipality', { exact: true }).fill('Dagupan');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByLabel('Number of floors').selectOption('2');
  await page.getByLabel('Ground floor area').fill('60');
  await page.getByLabel('Second floor area').fill('40');
  await expect(page.locator('.area-total')).toContainText('100');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByLabel('Available budget').fill('3000000');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('button', { name: 'Generate estimate', exact: true }).click();
  await expect(page.locator('.total-card h2')).toHaveText('₱3,300,000');
  await expect(page.locator('.budget-status')).toContainText('₱300,000 above');
  await page.getByRole('button', { name: 'Optimize my budget' }).click();
  await page.getByLabel('Finish package').selectOption('basic');
  await expect(page.locator('.comparison-total h2')).toHaveText('₱2,420,000');
  await expect(page.locator('.savings')).toContainText('₱880,000');
  await page.getByRole('button', { name: 'Restore original' }).click();
  await expect(page.locator('.comparison-total h2')).toHaveText('₱3,300,000');
  await page.getByLabel('Finish package').selectOption('basic');
  await expect(page.locator('.comparison-total h2')).toHaveText('₱2,420,000');
  await page.getByRole('button', { name: 'Use this scenario' }).click();
  await expect(page.locator('.total-card h2')).toHaveText('₱2,420,000');
  await page.getByRole('button', { name: 'Save project', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Full name').fill('Flow Test');
  await dialog.getByLabel('Email address').fill(`flow-${Date.now()}@example.test`);
  await dialog.getByLabel('Password', { exact: true }).fill('ExamplePassphrase-2026');
  await dialog.getByRole('button', { name: 'Create account', exact: true }).last().click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'Save project', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Project saved', exact: true })).toBeDisabled();
  const firstDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PDF report' }).click();
  expect((await firstDownload).suggestedFilename()).toMatch(/\.pdf$/);
  let projects = await (await page.request.get('/api/projects')).json();
  expect(projects.projects).toHaveLength(1);
  expect(projects.projects[0].estimate.total).toBe(2420000);
  await page.locator('.topbar').getByRole('button', { name: 'My projects', exact: true }).click();
  await page.getByRole('button', { name: 'View estimate' }).click();
  await page.reload();
  await expect(page.locator('.total-card h2')).toHaveText('₱2,420,000');
  const secondDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PDF report' }).click();
  await secondDownload;
  projects = await (await page.request.get('/api/projects')).json();
  expect(projects.projects).toHaveLength(1);
  await page.locator('.topbar').getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your next chapter starts with a plan.' })).toBeVisible();
  expect(await page.evaluate(() => sessionStorage.getItem('buildbudget-project'))).toBeNull();
  expect(await page.evaluate(() => sessionStorage.getItem('buildbudget-estimate'))).toBeNull();
  expect(errors).toEqual([]);
});

